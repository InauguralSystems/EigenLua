local function run(a, b, c) local n, last = 0, nil; local ok, e = pcall(function() for i = a, b, c do n = n + 1; last = i; if n > 5 then break end end end); return tostring(ok) .. " " .. n .. " " .. tostring(last) .. (ok and "" or (" " .. tostring(e))) end
print("nan+", run(1, 0/0, 1))
print("-1e300+", run(1, -1e300, 1))
print("1e300-", run(1, 1e300, -1))
print("-inf+", run(1, -math.huge, 1))
print("inf-", run(1, math.huge, -1))
print("inf+", run(math.maxinteger - 2, math.huge, 1))
print("-inf-", run(math.mininteger + 2, -math.huge, -1))
print("2^63+", run(math.maxinteger - 1, 2^63, 1))
print("-2^63-", run(math.mininteger + 1, -2^63, -1))
print("-2^63+", run(1, -2^63, 1))
print("1e300+", run(math.maxinteger, 1e300, 1))
print("3.5+", run(1, 3.5, 1))
print("-3.5-", run(-1, -3.5, -1))
print("big step", run(1, math.maxinteger, math.maxinteger))
print("neg big step", run(-1, math.mininteger, math.mininteger))
print("float loop", run(1.0, 3, 1))
print("float step", run(1, 3, 1.0))
