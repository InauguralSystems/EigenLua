-- surface: a close error caught in a coroutine does not defer an outer close
local co = coroutine.create(function()
  local a <close> = setmetatable({}, {__close = function(_, e) print("a", e) end})
  local ok, err = pcall(function()
    local b <close> = setmetatable({}, {__close = function(_, e)
      print("b", e)
      error("from b", 0)
    end})
    error("e1", 0)
  end)
  print("caught", ok, err)
  error("e2", 0)
end)
print(coroutine.resume(co))
print(coroutine.close(co))
