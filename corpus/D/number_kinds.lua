-- surface: integer result kinds of operators and standard-library boundaries
-- Population derived by walking Lua 5.4 manual sections 3.4.1--3.4.3 and
-- 6.4--6.7 (including 6.5), listing every integer-result rule and every
-- listed API whose integer argument/result boundary is observable here.
local function probe(tag, f)
  local r = table.pack(pcall(f))
  if not r[1] then print(tag, "ERROR", tostring(r[2]):gsub("^[^:]*:%d+: ", "")); return end
  local v = r[2]
  print(tag, math.type(v) or type(v), v)
end

