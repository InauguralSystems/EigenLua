-- surface: table library: a __len that does not return an integer makes luaL_len raise "object length is not an integer"
local t = setmetatable({}, {__len = function() return 2.5 end})
print(pcall(table.insert, t, 1))
print(pcall(table.remove, t))
print(pcall(table.concat, t))
print(pcall(table.unpack, t))
print(pcall(table.sort, t))
local t2 = setmetatable({}, {__len = function() return "3" end})
print(pcall(table.insert, t2, "v"), rawget(t2, 4))
local t3 = setmetatable({}, {__len = function() return 2.0 end})
table.insert(t3, "x")
print(rawget(t3, 3))
local t4 = setmetatable({}, {__len = function() return nil end})
print(pcall(table.insert, t4, 1))
