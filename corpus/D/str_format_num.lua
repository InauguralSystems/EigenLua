print(string.format("[%5.2f]", 3.14159))
print(string.format("[%5.2f]", -0.005))
print(string.format("[%-5s][%5s]", "ab", "cd"))
print(string.format("%g %g %g %g", 100000, 1e20, 0.0001, 2.5))
print(string.format("%i %i", 42, -7))
print(string.format("%c%c%c", 76, 117, 97))
print(string.format("%o %o", 8, 511))
print(string.format("%e %.2e", 12345.678, 0.000123))
print(string.format("%x %X %5d|%-5d|", 255, 255, 42, 42))
