-- surface: an error inside a __close run by coroutine.close closes that method's own variables before the next pending close (#73)
local function c(name, fail)
  return setmetatable({}, {__close = function(_, e)
    print(name, e)
    if fail then error(fail, 0) end
  end})
end
local function bclose(_, e)
  print("b", e)
  local inner <close> = c("inner", "ei")
  local inner2 <close> = c("inner2")
  error("eb", 0)
end
-- suspended coroutine
local co = coroutine.create(function()
  local a <close> = c("a")
  local b <close> = setmetatable({}, {__close = bclose})
  coroutine.yield(1)
end)
print("suspended", coroutine.resume(co))
print("suspended", coroutine.close(co))
-- suspended inside an xpcall: no message handler runs
co = coroutine.create(function()
  local a <close> = c("a")
  xpcall(function()
    local b <close> = setmetatable({}, {__close = bclose})
    coroutine.yield(2)
  end, function(m) print("handler", m); return "H" end)
end)
print("xpcall", coroutine.resume(co))
print("xpcall", coroutine.close(co))
-- errored coroutine: the closes deferred to coroutine.close, three of them
co = coroutine.create(function()
  local a <close> = c("a")
  local b <close> = setmetatable({}, {__close = bclose})
  local d <close> = c("d", "ed")
  error("e0", 0)
end)
print("errored", coroutine.resume(co))
print("errored", coroutine.close(co))
print("errored", coroutine.status(co), coroutine.close(co))
