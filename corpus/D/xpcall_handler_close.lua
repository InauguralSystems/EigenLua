-- surface: xpcall's message handler runs at the raise point, before the pending to-be-closed variables close (ldebug.c luaG_errormsg, then luaD_pcall's closes), and each __close receives the handler's result; an error in a __close passes through the handler again; pcall and a coroutine body have no handler; with os.exit in a __close the handler has already run
local function mk(n) return setmetatable({}, {__close = function(_, e) print("close", n, e) end}) end
print(xpcall(function()
  local q <close> = mk("q")
  local r <close> = mk("r")
  error("boom")
end, function(m) print("handler", m) return "H:" .. tostring(m) end))
print(xpcall(function()
  local q <close> = setmetatable({}, {__close = function(_, e) print("close q", e) error("inclose") end})
  error("boom2")
end, function(m) print("handler", m) return "H:" .. tostring(m) end))
print(xpcall(function()
  local q <close> = mk("q3")
  local function g() local z <close> = mk("z") error({1}) end
  g()
end, function(m) print("handler", type(m), debug.traceback("tb", 1):gsub("\n.*", "")) return "H" end))
print(pcall(function()
  local q <close> = mk("q4")
  error("e4")
end))
print(xpcall(function()
  local co = coroutine.wrap(function() local w <close> = mk("w") error("inco") end)
  co()
end, function(m) print("handler", m) return "H5" end))
print(xpcall(function()
  local q <close> = setmetatable({}, {__close = function(_, e) print("close", e) os.exit(0) end})
  error("last")
end, function(m) print("handler", m) return "H6" end))
print("not reached")
