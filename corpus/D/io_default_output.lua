-- surface: io: io.output and io.input change the default files that io.write, io.read and io.lines use (liolib.c getiofile)
local old = io.output()
print(old == io.stdout, io.input() == io.stdin)
print(io.output(io.stderr) == io.stderr)
io.write("this line goes to stderr, not stdout\n")
print("print still writes to stdout")
print(io.output() == io.stderr)
io.output(old)
io.write("back on stdout\n")
-- reading from a default input that is an output stream fails like C does
io.input(io.stdout)
print(io.read("l"))
io.input(io.stdin)
print(io.input() == io.stdin)
