-- surface: coroutine.close of a suspended coroutine: the error chain through three closes, pcall/xpcall around the yield, and nested frames (#73)
local function c(name, fail)
  return setmetatable({}, {__close = function(_, e)
    print(name, e)
    if fail ~= nil then error(fail, 0) end
  end})
end
local function run(label, body)
  local co = coroutine.create(body)
  print(label, "resume", coroutine.resume(co))
  print(label, "close", coroutine.close(co))
  print(label, "status", coroutine.status(co), "again", coroutine.close(co))
end
run("first", function() local a <close> = c("a"); local b <close> = c("b"); local d <close> = c("d", "ed"); coroutine.yield(1) end)
run("last", function() local a <close> = c("a", "ea"); local b <close> = c("b"); local d <close> = c("d"); coroutine.yield(1) end)
run("all", function() local a <close> = c("a", "ea"); local b <close> = c("b", "eb"); local d <close> = c("d", "ed"); coroutine.yield(1) end)
run("values", function() local a <close> = c("a"); local b <close> = c("b", 42); local d <close> = c("d", false); coroutine.yield(1) end)
local tv = {}
local co = coroutine.create(function()
  local a <close> = setmetatable({}, {__close = function(_, e) print("a got table", e == tv) end})
  local b <close> = c("b", tv)
  coroutine.yield(1)
end)
coroutine.resume(co)
local ok, e = coroutine.close(co)
print("table", ok, e == tv)
-- a pcall in the body does not catch an error raised by a close
run("pcall", function()
  local a <close> = c("a")
  print("pcall ret", pcall(function()
    local b <close> = c("b", "eb")
    coroutine.yield(2)
  end))
  print("not reached")
end)
-- the body's xpcall handler does not run for close errors
run("xpcall", function()
  local a <close> = c("a")
  print("xpcall ret", xpcall(function()
    local b <close> = c("b", "eb")
    coroutine.yield(3)
  end, function(m) print("handler", m); return "H" end))
end)
run("nested", function()
  local a <close> = c("a", "ea")
  local function inner()
    local b <close> = c("b", "eb")
    coroutine.yield(4)
  end
  inner()
end)
run("pos", function()
  local a <close> = c("a")
  local b <close> = setmetatable({}, {__close = function() error("withpos") end})
  coroutine.yield(5)
end)
run("forclose", function()
  for i in function(s, i) if i < 1 then return i + 1 end end, nil, 0, c("f", "ef") do
    local a <close> = c("a", "ea")
    coroutine.yield(i)
  end
end)
-- a close running after an earlier close error still cannot yield
run("yield", function()
  local a <close> = setmetatable({}, {__close = function(_, e)
    print("a", e, coroutine.isyieldable(), pcall(coroutine.yield, 9))
  end})
  local b <close> = c("b", "eb")
  coroutine.yield(6)
end)
