local function loop(tag, a, b, c)
  local ok, r = pcall(function() local n, last = 0, nil; for i = a, b, c do n = n + 1; last = i; if n > 10 then break end end; return n, last end)
  print(tag, ok, r, ok and select(2, pcall(function() local n, last = 0, nil; for i = a, b, c do n = n + 1; last = i; if n > 10 then break end end; return last end)) or "")
end
