-- surface: coroutines: coroutine.isyieldable is false inside a C function that calls back without a continuation (lua_isyieldable)
local co = coroutine.wrap(function()
  print("body", coroutine.isyieldable())
  string.gsub("a", "a", function() print("gsub callback", coroutine.isyieldable()) end)
  print("pcall", pcall(coroutine.isyieldable))
  local t = setmetatable({}, {__tostring = function() print("__tostring", coroutine.isyieldable()) return "t" end})
  print(tostring(t))
  print("after", coroutine.isyieldable())
end)
co()
print("main", coroutine.isyieldable())
